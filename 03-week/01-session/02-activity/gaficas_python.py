from google.colab import files
import pandas as pd
import matplotlib.pyplot as plt
from matplotlib.ticker import FormatStrFormatter

# Subir archivo
uploaded = files.upload()

# Leer CSV
df = pd.read_csv("CNST_Dataset.csv")

# Convertir a fecha
df["datetime"] = pd.to_datetime(df["datetime"])
df["date"] = df["datetime"].dt.date

# Agrupar por día y calcular velocidad promedio
speed_by_day = df.groupby("date")["speed"].mean().dropna()

# Graficar
plt.figure(figsize=(12,6))
speed_by_day.head(15).plot(kind="bar", color="orange")

plt.title("Velocidad promedio por día (primeros 15 días con datos)")
plt.xlabel("Fecha")
plt.ylabel("Velocidad promedio")

# Mostrar siempre con 2 decimales
plt.gca().yaxis.set_major_formatter(FormatStrFormatter('%.2f'))

plt.xticks(rotation=45, ha="right")
plt.tight_layout()
plt.show()

