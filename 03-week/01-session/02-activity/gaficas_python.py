import pandas as pd
import matplotlib.pyplot as plt

# Cargar el CSV
df = pd.read_csv("prog_book.csv")

# --- 3. Top 10 libros con más Reviews ---
# Reviews viene como object, hay que pasarlo a numérico
df["Reviews"] = pd.to_numeric(df["Reviews"], errors="coerce")

top_reviews = df.nlargest(10, "Reviews")[["Book_title", "Reviews"]]

plt.figure(figsize=(10,6))
plt.barh(top_reviews["Book_title"], top_reviews["Reviews"])
plt.title("Top 10 libros con más Reviews")
plt.xlabel("Cantidad de Reviews")
plt.ylabel("Título del libro")
plt.gca().invert_yaxis()  # para que el más grande quede arriba
plt.show()